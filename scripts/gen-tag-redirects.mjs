// Generate Cloudflare Pages redirects for language-only tags.
//
// Tag listings are language-scoped: EN at /tags/<tag>/, ZH at
// /zh/tags/<tag>/, ZH-TW at /zh-tw/tags/<tag>/. Post pages used to link
// every language's tags to /tags/<tag>/, so tags that exist only in
// Chinese posts (e.g. 安全, 开源) 404'd there and those URLs have been
// crawled/shared. Emit a 301 from each such legacy URL to the tag's own
// language listing. Runs right after `astro build` (see package.json
// "build") and writes straight into dist/ — putting the file in public/
// makes the Vite build try to parse it and fail.
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import kebabcase from "lodash.kebabcase";
import slugify from "slugify";

const slugifyStr = str =>
  /[^\x00-\x7F]/.test(str) ? kebabcase(str) : slugify(str, { lower: true });

async function tagSlugs(dir) {
  const slugs = new Set();
  let names;
  try {
    names = await readdir(dir);
  } catch {
    return slugs;
  }
  for (const name of names) {
    if (!name.endsWith(".md") && !name.endsWith(".mdx")) continue;
    const text = await readFile(path.join(dir, name), "utf-8");
    const fm = text.match(/^---\n([\s\S]*?)\n---/);
    if (!fm) continue;
    if (/^draft:\s*true\s*$/m.test(fm[1])) continue;
    const m = fm[1].match(/^tags:\s*\[([^\]]*)\]/m);
    if (!m) continue;
    for (const raw of m[1].matchAll(/"([^"]+)"|'([^']+)'/g)) {
      slugs.add(slugifyStr(raw[1] ?? raw[2]));
    }
  }
  return slugs;
}

const en = await tagSlugs("src/content/posts");
const zh = await tagSlugs("src/content/posts/zh");
const zhTw = await tagSlugs("src/content/posts/zh-tw");

const rules = [];
for (const slug of [...new Set([...zh, ...zhTw])].sort()) {
  if (en.has(slug)) continue; // EN tag page exists at /tags/<slug>/ already
  const lang = zh.has(slug) ? "zh" : "zh-tw";
  const enc = encodeURIComponent(slug);
  rules.push(`/tags/${enc}/ /${lang}/tags/${enc}/ 301`);
  rules.push(`/tags/${enc}/* /${lang}/tags/${enc}/:splat 301`);
}

const out = [
  "# Generated by scripts/gen-tag-redirects.mjs — do not edit by hand.",
  "# Legacy /tags/<tag>/ URLs for tags that only exist in Chinese posts",
  "# redirect to the language-scoped tag listing.",
  ...rules,
  "",
].join("\n");

await writeFile("dist/_redirects", out, "utf-8");
console.log(`[tag-redirects] wrote ${rules.length} rules to dist/_redirects`);
